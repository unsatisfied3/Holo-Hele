function resolveLanguage(): UiLanguage {
  return getSavedLanguage() === "ja" ? "ja" : "en";
}

function subscribe(listener: () => void) {
  window.addEventListener(LANGUAGE_CHANGE_EVENT, listener);
  window.addEventListener("storage", listener);
  return () => {
    window.removeEventListener(LANGUAGE_CHANGE_EVENT, listener);
    window.removeEventListener("storage", listener);
  };
}

function interpolate(template: string, values?: TranslationValues) {
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    values[key] == null ? match : String(values[key]),
  );
}

export function translate(
  message: string,
  values?: TranslationValues,
  language: UiLanguage = resolveLanguage(),
) {
  const template = language === "ja" ? japaneseMessages[message] ?? message : message;
  return interpolate(template, values);
}

export function useI18n() {
  const language = useSyncExternalStore<UiLanguage>(
    subscribe,
    resolveLanguage,
    () => "en",
  );

  useEffect(() => {
    document.documentElement.lang = language === "ja" ? "ja" : "en";
  }, [language]);

  return {
    language,
    locale: language === "ja" ? "ja-JP" : "en-US",
    t: (message: string, values?: TranslationValues) =>
      translate(message, values, language),
  };
}
